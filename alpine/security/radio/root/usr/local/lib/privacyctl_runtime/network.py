"""Apply explicitly owned lease state; migration and radio policy live elsewhere.

The caller must be the exclusive controller for protocol 196 on this interface.
On any failure it must block the radio BEFORE removing ``NetworkError.owned``.
Records are process-local capabilities: stale revisions cannot remove a renewed
lease. Persisted diagnostics contain addresses and belong in root-private state.
"""
